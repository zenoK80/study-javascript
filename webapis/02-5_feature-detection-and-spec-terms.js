export function render() {
  // ------------------------------------------------------------------------------------------
  // [meta]
  // ------------------------------------------------------------------------------------------
  // 내용: 기능 탐지, 스펙 용어, MDN에서 스펙까지 읽는 순서를 정리한다.
  // 링크: https://zeno.it.kr/javascript/web_apis/02_api-design-patterns
  // 배우고자 하는 것:
  // - 브라우저 이름보다 기능 존재 여부를 확인하는 습관을 익힌다.
  // - MUST, MUST NOT, SHOULD, MAY의 의미를 구분한다.
  // - MDN에서 스펙 원문까지 내려가는 흐름을 정리한다.
  // ------------------------------------------------------------------------------------------

  // ------------------------------------------------------------------------------------------
  // [용어정리]
  // - Feature Detection: 기능 존재 여부를 직접 확인하는 방식
  // - userAgent: 브라우저가 자신을 설명하는 문자열
  // - MUST: 반드시 그래야 함
  // - MUST NOT: 절대 그러면 안 됨
  // - SHOULD: 권장, 예외 가능
  // - MAY: 선택 사항
  // ------------------------------------------------------------------------------------------

  console.log("기능 탐지와 스펙 용어");

  // ------------------------------------------------------------------------------------------
  // [1]
  // ------------------------------------------------------------------------------------------
  // 내용: in 연산자로 기능이 있는지 확인한다.
  //
  // "IntersectionObserver" in window:
  // window 객체에 IntersectionObserver라는 기능이 있는지 확인한다.
  //
  // navigator.userAgent:
  // 브라우저 정보 문자열이다.
  // 하지만 이 문자열은 호환성 때문에 복잡하고 애매할 수 있어서,
  // 기능 지원 여부 판단에는 기능 탐지가 더 안전하다.
  // ------------------------------------------------------------------------------------------

  console.log("IntersectionObserver 지원 여부:", "IntersectionObserver" in window);
  console.log("fetch 지원 여부:", "fetch" in window);
  console.log("navigator.userAgent:", navigator.userAgent);

  // ------------------------------------------------------------------------------------------
  // [2]
  // ------------------------------------------------------------------------------------------
  // 내용: 스펙 용어를 표로 정리한다.
  //
  // 스펙 문서에서 대문자로 쓰인 MUST, SHOULD 같은 단어는 그냥 강조가 아니다.
  // 브라우저가 어떻게 구현해야 하는지 나타내는 규칙 용어다.
  // ------------------------------------------------------------------------------------------

  const specTerms = [
    { term: "MUST", meaning: "반드시 그래야 함", note: "어기면 구현 버그에 가깝다." },
    { term: "MUST NOT", meaning: "절대 그러면 안 됨", note: "금지 동작이다." },
    { term: "SHOULD", meaning: "권장, 예외 가능", note: "합당한 이유가 있으면 다를 수 있다." },
    { term: "MAY", meaning: "선택 사항", note: "브라우저마다 달라도 정상일 수 있다." }
  ];

  console.table(specTerms);

  // ------------------------------------------------------------------------------------------
  // [3]
  // ------------------------------------------------------------------------------------------
  // 내용: MDN에서 스펙까지 읽는 순서를 정리한다.
  //
  // 처음부터 스펙 원문만 보면 어렵다.
  // 보통은 MDN으로 사용법을 먼저 보고,
  // 애매한 동작만 Specifications 링크를 타고 스펙으로 내려간다.
  // ------------------------------------------------------------------------------------------

  const readingSteps = [
    "MDN에서 API 이름 검색",
    "기본 사용법과 예제 확인",
    "Specifications 링크로 스펙 원문 이동",
    "메서드 이름 또는 알고리즘 이름 검색",
    "번호가 붙은 알고리즘 단계 읽기",
    "Browser compatibility로 실제 지원 확인"
  ];

  console.table(readingSteps);
}

// ------------------------------------------------------------------------------------------
// [배운 것]
// - 기능 탐지는 브라우저 이름이 아니라 실제 기능 존재 여부를 확인하는 방식이다.
// - "기능이름" in 객체 형태로 해당 기능이 있는지 확인할 수 있다.
// - navigator.userAgent로 브라우저를 판단하는 방식은 문자열이 바뀌거나 애매할 수 있어 권장되지 않는다.
// - MUST는 스펙에서 반드시 지켜야 하는 동작을 뜻한다.
// - MUST NOT은 스펙에서 절대 하면 안 되는 동작을 뜻한다.
// - SHOULD는 권장이지만 합당한 이유가 있으면 구현이 달라질 수 있다는 뜻이다.
// - MAY는 브라우저가 선택해서 구현할 수 있는 동작이라는 뜻이다.
// - MDN은 사용 설명서에 가깝고, 스펙은 브라우저가 따라 구현하는 설계도에 가깝다.
// - 애매한 동작은 MDN의 Specifications 링크를 타고 스펙 원문 알고리즘 단계에서 확인한다.
// - 실제 브라우저 지원 여부는 MDN의 Browser compatibility 표에서 확인한다.
// ------------------------------------------------------------------------------------------
