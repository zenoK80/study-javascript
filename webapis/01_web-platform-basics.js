export function render() {
	// --------------------------------------------------------------------------------
	// [링크] https://zeno.it.kr/javascript/web_apis/01_web-platform-basics
	// [주제] 01. 브라우저 Web 플랫폼 지도: JS 엔진·DOM·Web API 경계
	// [날짜] 2026-09-10
	// --------------------------------------------------------------------------------

	// --------------------------------------------------------------------------------
	// [엔진이 하는 일 - 파싱,컴파일,실행]
	// --------------------------------------------------------------------------------
	// 엔진(engine, 실행기)는 자바스크립트 소스 코드를 받아 실제로 돌리는 프로그램입니다.
	// 크롬과 엣지의 V8, 파이어폭스의 SpiderMonkey, 사파리의 JavaScriptCore가 대표적입니다.
	// --------------------------------------------------------------------------------

	// --------------------------------------------------------------------------------
	// [엔진 내부 핵심 구조 2개]
	// --------------------------------------------------------------------------------
	// 콜스택(call stack,호출스택) - 지금 실행중인 함수들이 쌓이는 접시 더미. 함수를 부르면 위에 쌓고 끝나면 걷어낸다.
	// 힙(heap,더미) - 객체와 배열 같은 덩치 큰 값들이 저장되는 메모리 영역. 더 이상 아무도 참조하지 않는 값은 GC(Garbage Collection가비지컬렉션)이 알아서 회수
	// --------------------------------------------------------------------------------

	// --------------------------------------------------------------------------------
	// [실습]
	// --------------------------------------------------------------------------------
	// ECMAScript 언어가 정의하는 내장 객체 - 어떤 JS 환경에도 있음
	console.log(typeof Math); // object
	console.log(typeof JSON); // object
	console.log(typeof Promise); // function

	// 브라우저가 빌려주는 것 - 언어 명세에는 x
	console.log(typeof document) // object
	console.log(typeof fetch) // function
	console.log(typeof setTimeout) // function
	console.log(typeof localStorage) // object

	// 전역 객체의 정체
	console.log(window === globalThis) // true

	// 브라우저가 준 것은 window에 얹혀있다
	console.log("fetch" in window) // true
	console.log("document" in window) // true

	// 엔진이 멈추면 브라우저 UI도 함꼐 멈춘다.
	// 1. 스톱워치 시작 버튼 누름
	const 시작 = performance.now();
	let 합계 = 0;

	// 2. 컴퓨터한테 300만 번 동안 무식하게 더하기 작업을 시킴 (동기 반복문)
	for ( let i = 0; i < 3000000; i++){ 합계 += i;}

	// 3. 현재 시간에서 시작 시간을 빼서 '얼마나 걸렸는지' 계산하고 반올림(Math.round)함
	const 걸린시간 = Math.round(performance.now() - 시작);
	console.log("동기 반복" + 걸린시간 + "ms 동안 화면은 얼어 있었다");

	// 확인하고자 하는 것 :

	// performance.now() - 컴퓨터가 켜진 순간부터 지금까지 흐른 시간을 밀리초(ms, 1000분의 1초) 단위로 아주 정밀하게 재어주는 소수점 스톱워치
	// Date.now() - 지금이 몇 시 몇 분 몇 초야
	// --------------------------------------------------------------------------------

	// --------------------------------------------------------------------------------
	// [Web API - 브라우저가 빌려주는 능력]
	// --------------------------------------------------------------------------------
	// API(Application Programming Interface) - 서로 다른 두 세계가 만나 약속대로 대화하는 창구
	// Web API - 브라우저라는 주방이 자바스크립트라는 손님에게 내미는 메뉴판
	// 창구 뒤 실제 구현은 JS가 아니라 내부의 스택(C++로 짜인 코드)
	// --------------------------------------------------------------------------------

	// --------------------------------------------------------------------------------
	// [브라우저가 대신 한다]
	// --------------------------------------------------------------------------------
	// 주문서를 넘긴 뒤 내 콜 스택은 비어 있습니다. 네트워크 응답은 브라우저의 다른 스레드가 기다리고 있고, 내 자바스크립트는 그동안 다른 일을 합니다.
	// 응답이 오면 브라우저가 “결과 나왔습니다”라며 내가 맡겨둔 콜백(callback, 되부름 함수)을 큐(queue, 대기줄)에 넣어줍니다.
	// --------------------------------------------------------------------------------

	// --------------------------------------------------------------------------------
	// [이벤트루프]
	// --------------------------------------------------------------------------------
	// 콜스택은 하나입니다. 그런데 브라우저는 클릭,네트워크응답, 타이머 만료, 화면 갱신 모두 자바스크립트로 알려줘야 합니다.
	// 하나뿐인 자리에 순서대로 밀어 넣는 교통정리 장치가 필요한데 이 것이 이벤트 루프(event loop, 사건순환)
	// 콜스택(청구)가 비면 다음 번호를 부르고 창구에 앉은 손님이 안 일어나면 아무도 못 옴
	// 매크로테스크(macrotask,큰작업): 한 바퀴에 하나만 꺼낸다. 클릭이벤트 핸들러, setTimeout, 콜백, 스크립트 최초 실행
	// 마이크로테스크(microtask, 작은 작업): 매크로태스크 하나가 끝나면 큐가 완전히 빌 때까지 전부 실행. Promise의 then, await 이후 코드, queuMicrotask, MutaionObsever 콜백
	// 렌더링: 마이크로테스크까지 다 비운 뒤에 화면을 갱신할 기회가 옴
	// 무거운 반복문이 도는 동안 화면이 얼어붙는 이유이고, 스크롤·애니메이션 최적화가 전부 “메인 스레드를 비우기”라는 한 문장으로 수렴하는 이유
	// --------------------------------------------------------------------------------

	// --------------------------------------------------------------------------------
	// [실습2]
	// --------------------------------------------------------------------------------
	console.log("1.동기코드 - 지금 콜스택 위")

	setTimeout(()=>{
		console.log("5.매크로태스크(set time out)")
	},0);

	Promise.resolve().then(()=>{
		console.log("3.마이크로태스그(promise then)")
	})

	queueMicrotask(() => {
		console.log("4. 마이크로태스크(queueMicrotask)");
	});

	console.log("2. 동기 코드 — 여전히 같은 스택");

	// 클릭도 매크로태스크다. 핸들러 안의 Promise는
	// 그 핸들러가 끝난 직후 곧바로 소진된다.
	//
	// 주의:
	// document.getElementById("버튼")은 HTML 안에 id="버튼"인 요소가 있을 때만 동작한다.
	// 지금 index.html에는 그런 버튼이 없으므로 null이 나오고,
	// null.addEventListener(...)를 하려고 해서 에러가 났다.
	//
	// 그래서 여기서는 실제 DOM 버튼 대신 EventTarget으로 연습용 이벤트 대상을 만든다.
	const 클릭대상 = new EventTarget();

	클릭대상.addEventListener("click", () => {
		console.log("A. 클릭 핸들러 시작 — 새 매크로태스크");
		Promise.resolve().then(() => console.log("C. 핸들러가 만든 마이크로태스크"));
		console.log("B. 클릭 핸들러 끝");
	});

	클릭대상.dispatchEvent(new Event("click"));

	// 렌더링은 마이크로태스크를 전부 비운 다음에 온다
	requestAnimationFrame(() => {console.log("6. rAF — 다음 화면 갱신 직전");});

	// queueMicrotask : Promise 같은 복잡한 도구를 쓰지 않고, 순수하게 내 콜백 코드를 '마이크로태스크 대기실' 직통 맨 뒤에 줄 세워달라고 명령하는 내장 함수
	// Promise : 미래에 완료될 비동기 작업(서버 데이터 요청 등)의 결과를 담아두기로 약속하는 자바스크립트 표준 객체(영수증)
	// Promise.resolve() : 시간이 걸리는 대기 과정 없이, 호출하자마자 '이미 성공(완료) 처리된 영수증'을 그 즉시 발행해 주는 필살기 함수
	// Promise.resolve().then() : 이미 성공한 영수증에 대고 .then()을 붙여서, 내 알맹이 코드를 '마이크로태스크 대기실'에 꼼수로 집어넣어 먼저 실행시키기 위한 전통적인 문법 테크닉
	// --------------------------------------------------------------------------------

	// --------------------------------------------------------------------------------
	// [메인 스레드와 워커]
	// --------------------------------------------------------------------------------
	// 스레드: 컴퓨터 프로그램 내부에서 실제로 일(코드 계산)을 처리하는 '일꾼' 혹은 '작업실'의 단위입니다.
	// 워커: 메인 일꾼과 별개로, 배경(백그라운드)에서 무거운 계산 작업을 대신 처리해 줄 수 있도록 브라우저가 제공하는 '비서 일꾼(Web Worker)'입니다.
	// 메인스레드: 자바스크립트 코드가 기본적으로 실행되며, 화면을 그리고(렌더링) 사용자의 클릭·스크롤을 처리하는 '단 하나뿐인 핵심 일꾼'입니다. 이 자리가 무거운 코드로 막히면 화면이 얼어붙습니다.

	// 메인스레드(main thread, 주 실행 흐름)이름과 달리 자바스크립트만 돌리지 않습니다.
	// 자바스크립트 실행 - 스타일 계산과 레이아웃 - 대부분의 페인트 - 이벤트 디스패치(전달)
	// 전부 한 자리에서 순서대로 처리되므로 자바스크립트가 오래 돌면 전부 대기합니다.
	// --------------------------------------------------------------------------------

	// --------------------------------------------------------------------------------
	// [워커 — 진짜 병렬 실행]
	// --------------------------------------------------------------------------------
	// 자리를 늘리는 방법은 워커(Worker, 일꾼)뿐입니다. 워커는 별도 스레드에서 도는 독립된 자바스크립트 실행 환경입니다.
	// --------------------------------------------------------------------------------

	// --------------------------------------------------------------------------------
	// [origin - 보안의 기본 단위]
	// --------------------------------------------------------------------------------
	// 브라우저에서 내가 열어둔 탭과 낯선 광고 페이지가 같은 브라우저 프로세스에서 나란히 돕니다.
	// 아무 장치가 없다면 과오 페이지의 JS가 은행 페이지의 DOM을 읽어 계좌번호를 가져갈 수 있씁니다.
	// 이를 막는 단위가 origin,출저 입니다.
	// 오리진은 URL(Uniform Resource Locator, 자원 위치 지정자)의 세 조각으로 만들어집니다.
	// origin = scheme + host + port
	// scheme(통신방식) : https, http 프로토콜 이름
	// host(서버이름) : example.com 같은 도메인
	// port(포트접속번호) : 443, 800등 생략하면 스킴의 기본값
	// --------------------------------------------------------------------------------

	// --------------------------------------------------------------------------------
	// [Same-Origin Policy,SOP]
	// --------------------------------------------------------------------------------
	// 동일 출저 정책(Same origin policy,SOP) 다른 오리진의 DOM 읽기, 저장소 읽기, 응답 본문 읽기가 기본적으로 차단.
	// localStorage, IndexedDB, Cache Storage는 전부 오리진마다 별도아 공간을 가집니다.
	// --------------------------------------------------------------------------------

	// --------------------------------------------------------------------------------
	// [저장소별 자동 폭파 조건 & 수동 삭제 매칭]
	// --------------------------------------------------------------------------------
	// 1. 브라우저 끄면 폭파 (휘발성 저장소)
	//    - sessionStorage : 탭이나 브라우저 창을 닫는 순간 그 즉시 '자동 폭파'되어 흔적도 없이 사라짐.
	//    - Cookie (만료일 미지정 시) : 브라우저를 종료하면 '세션 쿠키'로 취급되어 자동으로 날아감.
	//
	// 2. 브라우저 꺼도 유지 (영구 파일 저장소)
	//    - localStorage, IndexedDB, Cache Storage : 컴퓨터를 꺼도 하드에 파일로 보관되어 유지됨.
	//
	// 3. 브라우저 설정 삭제 시 날아가는 조건 (수동 포맷 매칭)
	//    - [쿠키 및 사이트 데이터 삭제] 클릭 시 -> Cookie, localStorage, IndexedDB가 세트로 묶여서 한방에 '날아감'.
	//    - [캐시된 이미지 및 파일 삭제] 클릭 시 -> Cache Storage 보관함이 완전히 청소되어 '날아감'.
	//
	// 4. 기기 하드 용량이 부족할 때의 비상 청소 (강제 삭제)
	//    - 스마트폰이나 PC 용량이 꽉 차면, 브라우저가 임의로 장기 미방문 사이트의 localStorage와 IndexedDB를 통째로 '폭파시킴'.
	// --------------------------------------------------------------------------------

	// --------------------------------------------------------------------------------
	// [안전한 컨텍스트]
	// --------------------------------------------------------------------------------
	// 강력한 API(카메라,마이크,위치,Service Worker,crypto,subtle)는 안전한 컨텍스트(Secure contenxt)에서만 동작합니다.
	// https://이거나 localhost여야 한다는 뜻입니다. 중간에서 통신 가로채는 공격자가 있는 평문 연결에 권한을 주는 것은 위험하기 떄문입니다.
	// --------------------------------------------------------------------------------

	// --------------------------------------------------------------------------------
	// [마무리정리]
	// --------------------------------------------------------------------------------
	// 1. 하나뿐인 실행 자리(콜스택)의 교통정리
	//    - 자바스크립트는 일꾼이 하나(싱글 스레드)라 브라우저의 수많은 사건을 정렬할 '이벤트 루프'가 필수입니다.
	//    - 이벤트 루프는 [매크로태스크 1개 실행 -> 줄 서 있는 마이크로태스크 싹 다 털기 -> 렌더링 화면 갱신] 순서로 돕니다.
	//
	// 2. 마이크로태스크가 매크로태스크를 앞지르는 이유
	//    - 자바스크립트 파일 최초 실행 자체가 이미 첫 번째 매크로태스크로 취급되어 실행 중인 상태입니다.
	//    - 따라서 그 안에서 예약된 Promise.then이나 queueMicrotask(마이크로)가 setTimeout(매크로)보다 먼저 탈출합니다.
	//
	// 3. 웹 성능 최적화의 단 하나의 진리: "메인 스레드 비우기"
	//    - 메인 스레드는 자바스크립트 계산뿐만 아니라 화면 그리기(렌더링), 마우스 클릭, 스크롤 처리까지 도맡아 합니다.
	//    - 300만 번 더하기 같은 무거운 동기 코드가 자리를 차지하면 화면 갱신 단계로 내려가지 못해 브라우저가 벽돌(렉)이 됩니다.
	//
	// 4. 자리를 늘려 병렬로 일 처리하는 유일한 카드 '워커(Worker)'
	//    - 메인 직원이 무거운 장부 정리를 하느라 카운터(화면)를 마비시키는 것을 막기 위해 '보조 알바생(워커)'을 고용합니다.
	//    - 워커는 독자적인 별도 스레드에서 무거운 계산을 처리하되, 안전을 위해 화면(DOM)을 직접 건드리는 권한은 제한됩니다.
	// --------------------------------------------------------------------------------

}


