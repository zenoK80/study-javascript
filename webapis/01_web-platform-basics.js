export function render() {
  // ------------------------------------------------------------------------------------------
  // [meta]
  // ------------------------------------------------------------------------------------------
  // 내용: 브라우저 Web 플랫폼에서 JavaScript 엔진, DOM, Web API의 역할을 구분한다.
  // 링크: https://zeno.it.kr/javascript/web_apis/01_web-platform-basics
  // 배우고자 하는 것:
  // - JavaScript 엔진과 브라우저 기능의 차이를 이해한다.
  // - DOM이 무엇인지 확인한다.
  // - 대표적인 Web API를 직접 확인한다.
  // ------------------------------------------------------------------------------------------

  // ------------------------------------------------------------------------------------------
  // [용어정리]
  // - JavaScript Engine: JavaScript 코드를 해석하고 실행하는 엔진
  // - DOM: HTML 문서를 JavaScript에서 다룰 수 있게 만든 객체 구조
  // - Web API: 브라우저가 제공하는 기능
  // - window: 브라우저 전역 객체
  // ------------------------------------------------------------------------------------------

  // ------------------------------------------------------------------------------------------
  // [1]
  // ------------------------------------------------------------------------------------------
  // 내용: 브라우저의 전역 객체인 window를 확인한다.
  //
  // 결과:
  // typeof window → object
  // ------------------------------------------------------------------------------------------

  console.log(typeof window);

  // ------------------------------------------------------------------------------------------
  // [2]
  // ------------------------------------------------------------------------------------------
  // 내용: DOM의 핵심 객체인 document를 확인한다.
  //       document를 통해 HTML 요소를 조회하거나 수정할 수 있다.
  //
  // 결과:
  // typeof document → object
  // ------------------------------------------------------------------------------------------

  console.log(typeof document);
  console.log(document.title);

  // ------------------------------------------------------------------------------------------
  // [3]
  // ------------------------------------------------------------------------------------------
  // 내용: JavaScript 엔진 자체가 아니라 브라우저가 제공하는 Web API를 확인한다.
  //
  // 결과:
  // setTimeout → function
  // fetch      → function
  // localStorage → object
  // ------------------------------------------------------------------------------------------

  console.log(typeof setTimeout);
  console.log(typeof fetch);
  console.log(typeof localStorage);

  // ------------------------------------------------------------------------------------------
  // [4]
  // ------------------------------------------------------------------------------------------
  // 내용: DOM을 통해 현재 HTML 요소를 직접 찾는다.
  //
  // 결과:
  // #title 요소가 있으면 해당 HTMLElement가 출력된다.
  // ------------------------------------------------------------------------------------------

  const title = document.getElementById('title');

  console.log(title);

  // ------------------------------------------------------------------------------------------
  // [5]
  // ------------------------------------------------------------------------------------------
  // 내용: 브라우저 객체들이 window에 연결되어 있는지 확인한다.
  //
  // 결과:
  // window.document === document   → true
  // window.setTimeout === setTimeout → true
  // ------------------------------------------------------------------------------------------

  console.log(window.document === document);
  console.log(window.setTimeout === setTimeout);
}

// ------------------------------------------------------------------------------------------
// [배운 것]
// - JavaScript 엔진은 JavaScript 코드를 실행한다.
// - DOM은 HTML 문서를 JavaScript에서 다룰 수 있게 만든 객체 구조다.
// - document, fetch, setTimeout, localStorage 등은 브라우저가 제공하는 기능이다.
// - 브라우저 환경에서는 많은 Web API가 window를 통해 접근된다.
// ------------------------------------------------------------------------------------------
