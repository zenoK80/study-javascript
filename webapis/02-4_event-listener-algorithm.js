export function render() {
  // ------------------------------------------------------------------------------------------
  // [meta]
  // ------------------------------------------------------------------------------------------
  // 내용: addEventListener 스펙 알고리즘의 중복 등록 기준과 signal 자동 제거를 확인한다.
  // 링크: https://zeno.it.kr/javascript/web_apis/02_api-design-patterns
  // 배우고자 하는 것:
  // - 같은 이벤트 핸들러를 여러 번 등록하면 어떻게 되는지 확인한다.
  // - capture 옵션이 중복 판단에 들어간다는 점을 확인한다.
  // - signal 옵션으로 이벤트 리스너를 자동 제거하는 흐름을 확인한다.
  // ------------------------------------------------------------------------------------------

  // ------------------------------------------------------------------------------------------
  // [용어정리]
  // - EventTarget: 이벤트를 등록하고 직접 발생시킬 수 있는 객체
  // - addEventListener(): 이벤트 리스너를 등록하는 메서드
  // - listener: 이벤트가 발생했을 때 실행될 함수
  // - callback: 나중에 실행되도록 넘겨주는 함수
  // - capture: 이벤트 전파 단계 중 캡처링 단계에서 실행할지 정하는 옵션
  // - dispatchEvent(): 이벤트를 직접 발생시키는 메서드
  // ------------------------------------------------------------------------------------------

  console.log("addEventListener 스펙 규칙");

  // ------------------------------------------------------------------------------------------
  // [1]
  // ------------------------------------------------------------------------------------------
  // 내용: 연습용 이벤트 대상을 만든다.
  //
  // new EventTarget():
  // 화면 요소는 아니지만 이벤트를 등록하고 발생시킬 수 있는 객체를 만든다.
  // button 없이 이벤트 규칙만 연습할 때 쓰기 좋다.
  // ------------------------------------------------------------------------------------------

  const target = new EventTarget();
  let callCount = 0;

  // ------------------------------------------------------------------------------------------
  // [2]
  // ------------------------------------------------------------------------------------------
  // 내용: 이벤트가 발생했을 때 실행될 함수를 만든다.
  //
  // function handleSpecTest() { ... }
  // 함수 이름은 handleSpecTest다.
  //
  // callCount += 1:
  // callCount = callCount + 1 과 같은 뜻이다.
  // 함수가 실행될 때마다 실행 횟수를 1씩 늘린다.
  // ------------------------------------------------------------------------------------------

  function handleSpecTest() {
    callCount += 1;
    console.log(`handleSpecTest 실행 횟수: ${callCount}`);
  }

  // ------------------------------------------------------------------------------------------
  // [3]
  // ------------------------------------------------------------------------------------------
  // 내용: 같은 이벤트 타입, 같은 함수, 같은 capture 값으로 여러 번 등록한다.
  //
  // addEventListener("spec-test", handleSpecTest):
  // spec-test 이벤트가 발생하면 handleSpecTest 함수를 실행하라는 뜻이다.
  //
  // "spec-test":
  // 우리가 연습용으로 만든 이벤트 이름이다.
  // click처럼 브라우저가 기본으로 발생시키는 이벤트가 아니다.
  //
  // 스펙 중복 판단 기준:
  // - 이벤트 타입
  // - 콜백 함수
  // - capture 옵션
  //
  // 아래 3줄은 세 기준이 모두 같아서 실제로는 1개만 등록된다.
  // ------------------------------------------------------------------------------------------

  target.addEventListener("spec-test", handleSpecTest);
  target.addEventListener("spec-test", handleSpecTest);
  target.addEventListener("spec-test", handleSpecTest);

  // ------------------------------------------------------------------------------------------
  // [4]
  // ------------------------------------------------------------------------------------------
  // 내용: capture 값만 다르게 한 번 더 등록한다.
  //
  // { capture: true }:
  // capture 옵션을 true로 준다.
  //
  // 앞에서 등록한 리스너들은 capture 기본값이 false다.
  // 이번 리스너는 capture가 true라서 다른 리스너로 취급된다.
  //
  // 그래서 최종 등록 개수는:
  // capture false 리스너 1개
  // capture true 리스너 1개
  // 총 2개다.
  // ------------------------------------------------------------------------------------------

  target.addEventListener("spec-test", handleSpecTest, { capture: true });

  // ------------------------------------------------------------------------------------------
  // [5]
  // ------------------------------------------------------------------------------------------
  // 내용: 이벤트를 직접 발생시킨다.
  //
  // new Event("spec-test"):
  // spec-test라는 이름의 이벤트 객체를 만든다.
  //
  // target.dispatchEvent(...):
  // target에 등록된 spec-test 이벤트 리스너들을 실행시킨다.
  //
  // 결과:
  // handleSpecTest가 2번 실행된다.
  // ------------------------------------------------------------------------------------------

  target.dispatchEvent(new Event("spec-test"));

  console.log("최종 실행 횟수:", callCount); // 2

  // ------------------------------------------------------------------------------------------
  // [6]
  // ------------------------------------------------------------------------------------------
  // 내용: signal 옵션으로 이벤트 리스너를 자동 제거한다.
  //
  // addEventListener 세 번째 인자에는 signal 옵션을 넣을 수 있다.
  // 이 signal이 abort되면 연결된 이벤트 리스너가 자동으로 제거된다.
  // ------------------------------------------------------------------------------------------

  const autoRemoveTarget = new EventTarget();
  const autoRemoveController = new AbortController();
  let autoRemoveCount = 0;

  function handleAutoRemove() {
    autoRemoveCount += 1;
    console.log(`handleAutoRemove 실행 횟수: ${autoRemoveCount}`);
  }

  autoRemoveTarget.addEventListener("auto-remove", handleAutoRemove, {
    signal: autoRemoveController.signal
  });

  autoRemoveTarget.dispatchEvent(new Event("auto-remove"));
  autoRemoveController.abort("이벤트 리스너 제거");
  autoRemoveTarget.dispatchEvent(new Event("auto-remove"));

  console.log("abort 후 자동 제거 확인:", autoRemoveCount); // 1
}

// ------------------------------------------------------------------------------------------
// [배운 것]
// - EventTarget은 이벤트를 등록하고 직접 발생시킬 수 있는 객체다.
// - addEventListener()는 이벤트 리스너를 등록하는 메서드다.
// - listener 또는 callback은 이벤트가 발생했을 때 실행될 함수다.
// - dispatchEvent()는 이벤트를 직접 발생시키는 메서드다.
// - new Event("이름")은 해당 이름을 가진 이벤트 객체를 만든다.
// - addEventListener는 이벤트 타입, 콜백 함수, capture 옵션이 모두 같으면 중복 등록으로 보고 다시 추가하지 않는다.
// - capture 옵션이 다르면 같은 함수라도 별개의 이벤트 리스너로 등록될 수 있다.
// - once, passive, signal은 중복 판단 기준에 들어가지 않는다.
// - addEventListener 옵션에 signal을 넘기면 abort()가 실행될 때 이벤트 리스너가 자동 제거된다.
// ------------------------------------------------------------------------------------------
