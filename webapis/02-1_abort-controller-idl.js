export function render() {
  // ------------------------------------------------------------------------------------------
  // [meta]
  // ------------------------------------------------------------------------------------------
  // 내용: AbortController를 통해 Web IDL 표현이 실제 JavaScript 객체에서 어떻게 보이는지 확인한다.
  // 링크: https://zeno.it.kr/javascript/web_apis/02_api-design-patterns
  // 배우고자 하는 것:
  // - AbortController, signal, abort의 기본 의미를 이해한다.
  // - readonly 속성은 다른 값으로 덮어쓸 수 없다는 점을 확인한다.
  // - getter와 setter가 무엇인지 아주 가볍게 확인한다.
  // ------------------------------------------------------------------------------------------

  // ------------------------------------------------------------------------------------------
  // [용어정리]
  // - AbortController: 진행 중인 작업을 취소하기 위한 컨트롤러
  // - signal: 취소 상태를 담는 신호 객체
  // - abort(): 취소 버튼을 누르는 메서드
  // - readonly: 읽기 전용이라는 뜻
  // - prototype: 같은 생성자로 만든 객체들이 함께 쓰는 공용 기능 보관함
  // - getter: 속성을 읽을 때 실행되는 함수
  // - setter: 속성에 값을 대입할 때 실행되는 함수
  // ------------------------------------------------------------------------------------------

  console.log("AbortController와 Web IDL");

  // ------------------------------------------------------------------------------------------
  // [1]
  // ------------------------------------------------------------------------------------------
  // 내용: AbortController를 만들고 signal 상태를 확인한다.
  //
  // 결과:
  // 취소 전 signal.aborted -> false
  // 취소 후 signal.aborted -> true
  // signal.reason -> 취소 사유
  // ------------------------------------------------------------------------------------------

  const controller = new AbortController();

  console.log("취소 전:", controller.signal.aborted); // false

  controller.abort("사용자가 취소함");

  console.log("취소 후:", controller.signal.aborted); // true
  console.log("취소 이유:", controller.signal.reason); // 사용자가 취소함

  // ------------------------------------------------------------------------------------------
  // [2]
  // ------------------------------------------------------------------------------------------
  // 내용: signal은 같은 객체를 계속 돌려준다.
  //
  // 결과:
  // controller.signal === controller.signal -> true
  // ------------------------------------------------------------------------------------------

  console.log("signal은 같은 객체인가?", controller.signal === controller.signal); // true

  // ------------------------------------------------------------------------------------------
  // [3]
  // ------------------------------------------------------------------------------------------
  // 내용: signal은 readonly라서 다른 값으로 덮어쓸 수 없다.
  //
  // try...catch:
  // 에러가 날 수 있는 코드를 안전하게 실행하는 문법이다.
  //
  // catch (error):
  // try 안에서 발생한 에러를 error라는 변수로 받는다는 뜻이다.
  //
  // 결과:
  // signal은 원본 객체 그대로 유지된다.
  // ------------------------------------------------------------------------------------------

  const originalSignal = controller.signal;

  try {
    controller.signal = "덮어쓰기 시도";
  } catch (error) {
    console.log("readonly 대입 에러:", error.name);
  }

  console.log("signal 유지됨?", controller.signal === originalSignal); // true

  // ------------------------------------------------------------------------------------------
  // [4]
  // ------------------------------------------------------------------------------------------
  // 내용: signal 속성 설명서를 확인한다.
  //
  // Object.getOwnPropertyDescriptor(첫 번째 인자, 두 번째 인자)
  // 첫 번째 인자: 어느 객체에서 찾을 것인가
  // 두 번째 인자: 그 객체의 어떤 속성을 찾을 것인가
  //
  // AbortController.prototype:
  // AbortController로 만든 객체들이 함께 쓰는 공용 기능 보관함이다.
  //
  // "signal":
  // 그 공용 기능 보관함에서 signal이라는 속성 설명서를 찾겠다는 뜻이다.
  //
  // 결과:
  // get -> function
  // set -> undefined
  //
  // 뜻:
  // 읽을 때 실행되는 getter는 있지만, 대입할 때 실행되는 setter는 없다.
  // 그래서 controller.signal = 값 으로 바꿔 끼울 수 없다.
  // ------------------------------------------------------------------------------------------

  const descriptor = Object.getOwnPropertyDescriptor(
    AbortController.prototype,
    "signal"
  );

  console.log("getter 타입:", typeof descriptor.get); // function
  console.log("setter 타입:", typeof descriptor.set); // undefined
}

// ------------------------------------------------------------------------------------------
// [배운 것]
// - AbortController는 작업을 취소하기 위한 컨트롤러다.
// - signal은 취소 상태를 담는 신호 객체다.
// - abort()를 실행하면 signal.aborted가 true가 된다.
// - signal.reason에는 abort("이유")로 넘긴 취소 이유가 들어간다.
// - readonly 속성은 다른 값으로 덮어쓸 수 없다.
// - try...catch는 에러가 나도 코드가 멈추지 않게 잡아주는 문법이다.
// - catch (error)의 error는 발생한 에러 객체를 담는 변수다.
// - prototype은 객체들이 함께 쓰는 공용 기능 보관함이다.
// - Object.getOwnPropertyDescriptor()는 속성 설명서를 꺼내보는 메서드다.
// - getter는 속성을 읽을 때 실행되는 함수다.
// - setter는 속성에 값을 대입할 때 실행되는 함수다.
// ------------------------------------------------------------------------------------------
