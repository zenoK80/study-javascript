export function render() {
  // ------------------------------------------------------------------------------------------
  // [meta]
  // ------------------------------------------------------------------------------------------
  // 내용: Web API 옵션 객체와 dictionary, boolean 변환 함정을 확인한다.
  // 링크: https://zeno.it.kr/javascript/web_apis/02_api-design-patterns
  // 배우고자 하는 것:
  // - addEventListener의 세 번째 인자 옵션 객체를 이해한다.
  // - once 옵션의 의미를 확인한다.
  // - 문자열 "false"가 boolean으로는 true가 될 수 있음을 확인한다.
  // ------------------------------------------------------------------------------------------

  // ------------------------------------------------------------------------------------------
  // [용어정리]
  // - dictionary: 옵션 객체의 모양을 정의하는 스펙 용어
  // - option object: { once: true } 같은 옵션 묶음 객체
  // - boolean: true 또는 false 값
  // - Boolean(): 값을 true 또는 false로 변환해보는 함수
  // - once: 이벤트 리스너를 한 번만 실행할지 정하는 옵션
  // ------------------------------------------------------------------------------------------

  console.log("옵션 딕셔너리와 boolean 변환");

  // ------------------------------------------------------------------------------------------
  // [1]
  // ------------------------------------------------------------------------------------------
  // 내용: Boolean()으로 여러 값을 true/false로 바꿔본다.
  //
  // 결과:
  // Boolean(false) -> false
  // Boolean("false") -> true
  // Boolean("") -> false
  // Boolean("hello") -> true
  // ------------------------------------------------------------------------------------------

  console.log(Boolean(false));
  console.log(Boolean("false"));
  console.log(Boolean(""));
  console.log(Boolean("hello"));

  // ------------------------------------------------------------------------------------------
  // [2]
  // ------------------------------------------------------------------------------------------
  // 내용: once 옵션은 문자열이 아니라 진짜 boolean을 넣어야 한다.
  //
  // { once: true }
  // 이벤트가 발생해도 함수는 한 번만 실행된다.
  //
  // { once: false }
  // 이벤트가 발생할 때마다 함수가 실행된다.
  //
  // { once: "false" }
  // 사람이 보기엔 false 같지만 문자열이다.
  // 비어 있지 않은 문자열은 Boolean 변환 시 true가 된다.
  // ------------------------------------------------------------------------------------------

  const options = { once: "false" };

  console.log("options.once 원래 값:", options.once); // false 문자열
  console.log("Boolean(options.once):", Boolean(options.once)); // true

  // ------------------------------------------------------------------------------------------
  // [3]
  // ------------------------------------------------------------------------------------------
  // 내용: once: "false"가 실제로 한 번만 실행되는지 확인한다.
  //
  // EventTarget:
  // 이벤트를 등록하고 직접 발생시킬 수 있는 연습용 객체다.
  //
  // dispatchEvent(new Event("practice")):
  // practice라는 이름의 이벤트를 직접 발생시킨다.
  //
  // 결과:
  // 이벤트를 두 번 발생시켜도 count는 1이 된다.
  // ------------------------------------------------------------------------------------------

  const target = new EventTarget();
  let count = 0;

  target.addEventListener(
    "practice",
    () => {
      count += 1;
      console.log(`practice 이벤트 실행 횟수: ${count}`);
    },
    { once: "false" }
  );

  target.dispatchEvent(new Event("practice"));
  target.dispatchEvent(new Event("practice"));

  console.log("최종 실행 횟수:", count); // 1
}

// ------------------------------------------------------------------------------------------
// [배운 것]
// - dictionary는 옵션 객체의 모양을 정의하는 스펙 용어다.
// - addEventListener의 세 번째 인자에는 옵션 객체를 넣을 수 있다.
// - once 옵션은 이벤트를 한 번만 실행할지 정하는 boolean 옵션이다.
// - boolean은 true 또는 false 값이다.
// - Boolean()은 값을 true 또는 false로 변환해보는 함수다.
// - 문자열 "false"는 Boolean으로 바꾸면 true가 된다.
// - Web API 옵션에는 문자열 "true", "false"보다 진짜 true, false 값을 넣는 것이 안전하다.
// - EventTarget은 이벤트를 등록하고 직접 발생시킬 수 있는 객체다.
// - dispatchEvent()는 이벤트를 직접 발생시키는 메서드다.
// ------------------------------------------------------------------------------------------
