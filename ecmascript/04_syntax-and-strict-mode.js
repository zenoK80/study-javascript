export function render() {
  // ------------------------------------------------------------------------------------------
  // [meta]
  // ------------------------------------------------------------------------------------------
  // 내용: strict mode와 script/module의 차이, 안전한 JavaScript 작성 규칙을 확인한다.
  // 링크: https://zeno.it.kr/javascript/ECMAscript/04_syntax-and-strict-mode
  // 배우고자 하는 것:
  // - strict mode가 무엇인지 이해한다.
  // - 일반 script와 ES Module의 차이를 확인한다.
  // - 실수를 줄이는 기본 작성 규칙을 확인한다.
  // ------------------------------------------------------------------------------------------

  // ------------------------------------------------------------------------------------------
  // [용어정리]
  // - strict mode: JavaScript를 더 엄격한 규칙으로 실행하는 모드
  // - script: 일반 JavaScript 실행 방식
  // - module: import/export를 사용할 수 있는 ES Module 실행 방식
  // - ReferenceError: 존재하지 않는 변수 등을 사용할 때 발생하는 오류
  // ------------------------------------------------------------------------------------------

  // ------------------------------------------------------------------------------------------
  // [1]
  // ------------------------------------------------------------------------------------------
  // 내용: strict mode에서는 선언하지 않은 변수에 값을 넣을 수 없다.
  //
  // 결과:
  // ReferenceError
  // ------------------------------------------------------------------------------------------

  function strictTest() {
    'use strict';

    try {
      undeclaredValue = 10;
    } catch (error) {
      console.log(error.name);
    }
  }

  strictTest();

  // ------------------------------------------------------------------------------------------
  // [2]
  // ------------------------------------------------------------------------------------------
  // 내용: strict mode 함수에서 일반 함수 호출의 this를 확인한다.
  //
  // 결과:
  // undefined
  // ------------------------------------------------------------------------------------------

  function checkThis() {
    'use strict';

    console.log(this);
  }

  checkThis();

  // ------------------------------------------------------------------------------------------
  // [3]
  // ------------------------------------------------------------------------------------------
  // 내용: ES Module은 기본적으로 strict mode로 실행된다.
  //       현재 파일도 import()로 불러오는 ES Module이므로 별도의
  //       'use strict' 없이 strict mode 규칙이 적용된다.
  //
  // 결과:
  // ReferenceError
  // ------------------------------------------------------------------------------------------

  try {
    moduleUndeclaredValue = 20;
  } catch (error) {
    console.log(error.name);
  }

  // ------------------------------------------------------------------------------------------
  // [4]
  // ------------------------------------------------------------------------------------------
  // 내용: ES Module에서는 최상위 this가 window가 아니라 undefined다.
  //
  // 결과:
  // undefined
  // ------------------------------------------------------------------------------------------

  console.log(this);

  // ------------------------------------------------------------------------------------------
  // [5]
  // ------------------------------------------------------------------------------------------
  // 내용: const와 let을 기본으로 사용하고 var 사용은 피하는 습관을 확인한다.
  //       값이 다시 바뀌지 않으면 const, 재할당이 필요하면 let을 사용한다.
  //
  // 결과:
  // JavaScript
  // 2
  // ------------------------------------------------------------------------------------------

  const language = 'JavaScript';
  let count = 1;

  count = 2;

  console.log(language);
  console.log(count);
}

// ------------------------------------------------------------------------------------------
// [배운 것]
// - strict mode는 실수하기 쉬운 JavaScript 동작을 더 엄격하게 제한한다.
// - ES Module은 기본적으로 strict mode로 실행된다.
// - Module의 최상위 this는 undefined다.
// - 선언하지 않은 변수 사용은 ReferenceError를 발생시킨다.
// - 기본은 const, 재할당이 필요할 때 let을 사용한다.
// ------------------------------------------------------------------------------------------
