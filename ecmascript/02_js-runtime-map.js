export function render() {
  // ------------------------------------------------------------------------------------------
  // [meta]
  // ------------------------------------------------------------------------------------------
  // 내용: JavaScript 런타임의 기본 구조와 코드 실행 순서를 확인한다.
  // 링크: https://zeno.it.kr/javascript/ECMAscript/02_js-runtime-map
  // 배우고자 하는 것:
  // - Call Stack이 어떤 순서로 함수 실행을 처리하는지 확인한다.
  // - 동기 코드와 비동기 코드의 실행 순서를 확인한다.
  // - Microtask와 Task의 차이를 확인한다.
  // ------------------------------------------------------------------------------------------

  // ------------------------------------------------------------------------------------------
  // [용어정리]
  // - Call Stack: 현재 실행 중인 함수들이 쌓이는 공간
  // - 동기 코드: 작성된 순서대로 바로 실행되는 코드
  // - Microtask: Promise.then() 같은 작업이 대기하는 큐
  // - Task: setTimeout(), 이벤트 같은 작업이 대기하는 큐
  // - Event Loop: Call Stack과 Queue를 확인하면서 실행할 작업을 넘겨주는 구조
  // ------------------------------------------------------------------------------------------

  console.log('JavaScript Runtime Map');

  // ------------------------------------------------------------------------------------------
  // [1]
  // ------------------------------------------------------------------------------------------
  // 내용: Call Stack의 실행 순서를 확인한다.
  //       first → second → third 순서로 함수가 호출되고,
  //       실행이 끝날 때는 반대로 third → second → first 순서로 빠져나온다.
  //
  // 결과:
  // first 시작
  // second 시작
  // third 실행
  // Call Stack 확인 ...
  // second 끝
  // first 끝
  // ------------------------------------------------------------------------------------------

  function first() {
    console.log('first 시작');
    second();
    console.log('first 끝');
  }

  function second() {
    console.log('second 시작');
    third();
    console.log('second 끝');
  }

  function third() {
    console.log('third 실행');
    console.log(new Error('Call Stack 확인').stack);
  }

  first();

  // ------------------------------------------------------------------------------------------
  // [2]
  // ------------------------------------------------------------------------------------------
  // 내용: 동기 코드 → Microtask → Task 순서로 실행되는지 확인한다.
  //
  //       Promise.then()의 콜백은 Microtask Queue에 들어간다.
  //       setTimeout()의 콜백은 Task Queue에 들어간다.
  //       현재 동기 코드가 모두 끝난 뒤 Microtask를 먼저 실행하고,
  //       그 다음 Task를 실행한다.
  //
  // 결과:
  // 1. 동기 코드 시작
  // 2. 동기 코드 끝
  // 3. Promise
  // 4. setTimeout
  // ------------------------------------------------------------------------------------------

  console.log('1. 동기 코드 시작');

  setTimeout(() => {
    console.log('4. setTimeout');
  }, 0);

  Promise.resolve().then(() => {
    console.log('3. Promise');
  });

  console.log('2. 동기 코드 끝');
}

// ------------------------------------------------------------------------------------------
// [배운 것]
// - JavaScript는 현재 실행 중인 동기 코드를 먼저 끝낸다.
// - 함수 호출은 Call Stack에 쌓이고, 끝난 함수부터 빠져나온다.
// - Promise.then()은 Microtask로 처리된다.
// - setTimeout()은 Task로 처리된다.
// - 실행 순서는 기본적으로 동기 코드 → Microtask → Task이다.
// ------------------------------------------------------------------------------------------
