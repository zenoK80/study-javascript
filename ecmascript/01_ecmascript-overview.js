export function render() {
  // ------------------------------------------------------------------------------------------
  // [meta]
  // ------------------------------------------------------------------------------------------
  // 내용: ECMAScript 표준과 JavaScript 실행 환경의 기본 개념을 확인한다.
  // 링크: https://zeno.it.kr/javascript/ECMAscript/01_ecmascript-overview
  // 배우고자 하는 것:
  // - ECMAScript가 무엇인지 이해한다.
  // - ECMAScript 기능과 Web API를 구분한다.
  // - JavaScript Number의 특징을 확인한다.
  // ------------------------------------------------------------------------------------------

  // ------------------------------------------------------------------------------------------
  // [용어정리]
  // - ECMAScript: JavaScript의 문법과 동작을 정의한 표준
  // - Web API: 브라우저가 JavaScript에 추가로 제공하는 기능
  // - Number: JavaScript의 기본 숫자 타입
  // - typeof: 값의 타입을 문자열로 확인하는 연산자
  // ------------------------------------------------------------------------------------------

  console.log('ECMAScript Overview');

  // ------------------------------------------------------------------------------------------
  // [1]
  // ------------------------------------------------------------------------------------------
  // 내용: ECMAScript가 제공하는 기본 객체의 타입을 확인한다.
  //
  // 결과:
  // Object  → function
  // Array   → function
  // Promise → function
  // Symbol  → function
  // ------------------------------------------------------------------------------------------

  console.log(typeof Object);
  console.log(typeof Array);
  console.log(typeof Promise);
  console.log(typeof Symbol);

  // ------------------------------------------------------------------------------------------
  // [2]
  // ------------------------------------------------------------------------------------------
  // 내용: 브라우저가 제공하는 Web API의 타입을 확인한다.
  //       document, console, setTimeout은 ECMAScript 자체 기능이 아니라
  //       브라우저 환경에서 제공된다.
  //
  // 결과:
  // document   → object
  // console    → object
  // setTimeout → function
  // ------------------------------------------------------------------------------------------

  console.log(typeof document);
  console.log(typeof console);
  console.log(typeof setTimeout);

  // ------------------------------------------------------------------------------------------
  // [3]
  // ------------------------------------------------------------------------------------------
  // 내용: JavaScript의 소수 계산에서 오차가 발생할 수 있음을 확인한다.
  //
  // 결과:
  // 0.1 + 0.2         → 0.30000000000000004
  // 0.1 + 0.2 === 0.3 → false
  // ------------------------------------------------------------------------------------------

  console.log(0.1 + 0.2);
  console.log(0.1 + 0.2 === 0.3);

  // ------------------------------------------------------------------------------------------
  // [4]
  // ------------------------------------------------------------------------------------------
  // 내용: JavaScript Number가 안전하게 표현할 수 있는 최대 정수를 확인한다.
  //
  // 결과:
  // 9007199254740991
  // ------------------------------------------------------------------------------------------

  console.log(Number.MAX_SAFE_INTEGER);
}

// ------------------------------------------------------------------------------------------
// [배운 것]
// - ECMAScript는 JavaScript의 표준이다.
// - Object, Array, Promise, Symbol 등은 ECMAScript에서 정의한다.
// - document, console, setTimeout 등은 브라우저가 제공하는 Web API다.
// - JavaScript의 소수 계산에는 부동소수점 오차가 생길 수 있다.
// - Number.MAX_SAFE_INTEGER까지의 정수를 안전하게 표현할 수 있다.
// ------------------------------------------------------------------------------------------
