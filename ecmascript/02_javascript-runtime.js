export function render() {
	// --------------------------------------------------------------------------------
	// [링크] https://zeno.it.kr/javascript/ECMAscript/02_js-runtime-map
	// [주제] JavaScript 런타임 지도: 엔진, 호스트, 이벤트 루프 맛보기
	// [날짜] 2026-09-11
	// --------------------------------------------------------------------------------

	// --------------------------------------------------------------------------------
	// [런타임]
	// --------------------------------------------------------------------------------
	// 런타임(run time): 컴파일 또는 빌드를 마친 프로그램이 실제로 실행되는 시간(시점)
	// 파싱타임(parse time): 소스 코드를 분석하여 컴퓨터가 이해할 수 있는 구조로 해석하는 시간
	// 실행환경: 프로그램이 구동되는 환경 (예: 브라우저, Node.js, OS 등)
	// 런타임 = 엔진 + 호스트 제공 기능
	// --------------------------------------------------------------------------------

	// --------------------------------------------------------------------------------
	// [JavaScript 런타임 구성 및 동작 원리 요약]
	// --------------------------------------------------------------------------------
	// 1. 런타임: 엔진(코어)과 호스트(브라우저/Node.js)의 결합 (요리사(싱글 스레드)와 주방 설비)
	// 2. 엔진 내부: 함수를 쌓는 콜 스택(LIFO)과 객체가 저장되는 힙(Heap)
	// 3. 싱글 스레드 & 런투컴플리션: 한 번에 하나씩, 중간에 끊기지 않고 실행
	// 4. 이벤트 루프: 스택이 비면 마이크로태스크 큐를 우선 비운 뒤 태스크 큐 처리
	// --------------------------------------------------------------------------------

	// --------------------------------------------------------------------------------
	// [엔진 안쪽 - 콜스택과 힙]
	// --------------------------------------------------------------------------------
	// 콜스택 - 실행 중인 함수를 쌓는 접시탑
	// 스택(stack): 쌓아올린 더미, 나중에 넣은 것을 먼저 꺼내는 규칙을 가진 구조.
	// LIFO(Last In First Out) 마지막에 들어온 것이 먼저 나감
	// - 함수 호출 = 실행 컨텍스트(실행 정보 묶음) 생성 및 스택 맨 위에 푸시(Push)
	// - 함수 종료 = 실행 컨텍스트가 스택에서 팝(Pop)되어 제거됨
	// --------------------------------------------------------------------------------
	//
	// --------------------------------------------------------------------------------

	// --------------------------------------------------------------------------------
	// [실습] 콜스택의 동작 원리와 한계 측정하기
	// --------------------------------------------------------------------------------
	// [1단계: 스택이 쌓이고 빠지는 과정 추적]
	// 깊이에 따라 들여쓰기를 조절하여 콘솔에 출력하는 함수입니다.
	function 깊이표시(단계, 이름) {
	  // .repeat(단계)로 단계가 깊어질수록 공백(스페이스 2칸)을 앞에 붙여 밀어냅니다.
	  console.log("  ".repeat(단계) + "→ " + 이름 + " 시작");
	}

	function 첫번째() {
	  // 콜스택 맨 밑에 '첫번째' 함수가 쌓임
	  깊이표시(0, "첫번째");
	  // '첫번째'가 끝나기 전에 '두번째'를 호출하여 위로 쌓음
	  두번째();
	  // 가장 마지막으로 스택에서 완전히 제거됨
	  console.log("→ 첫번째 끝 (스택에서 팝)");
	}

	function 두번째() {
	  // '첫번째' 위에 '두번째' 함수가 쌓임
	  깊이표시(1, "두번째");
	  // '두번째'가 끝나기 전에 '세번째'를 호출하여 위로 쌓음
	  세번째();
	  // 세번째가 빠진 후, 두번째로 스택에서 제거됨
	  console.log("  → 두번째 끝 (스택에서 팝)");
	}

	function 세번째() {
	  // 콜스택 맨 위에 '세번째' 함수가 쌓임 (현재 스택 최상단)
	  깊이표시(2, "세번째");

	  // %c를 사용하면 브라우저 콘솔에서 글자 색상 스타일(여기서는 cyan)을 적용할 수 있습니다.
	  console.log("%c[스택 사진 촬영]", "color: cyan; font-weight: bold;");

	  // new Error().stack은 현재 이 시점에 스택에 쌓여있는 함수들의 계보(추적 기록)를 텍스트로 보여줍니다.
	  console.log(new Error().stack);

	  // 가장 마지막에 쌓였으므로 제일 먼저 스택에서 제거됨
	  console.log("    → 세번째 끝 (스택에서 팝)");
	}
	// 1단계 실행: 함수들이 위로 순서대로 쌓였다가 가장 안쪽(위쪽)부터 차례대로 풀립니다.
	첫번째();

	// ================================================================================
	// [▼ 1단계 콘솔 실제 출력 결과창 ▼]
	//
	// → 첫번째 시작
	//   → 두번째 시작
	//     → 세번째 시작
	// [스택 사진 촬영] (하늘색 글씨로 출력됨)
	// Error
	//     at 세번째 (파일명.js:28)  <-- 현재 실행 중인 맨 위 가방
	//     at 두번째 (파일명.js:22)  <-- 그 아래 대기 중인 가방
	//     at 첫번째 (파일명.js:15)  <-- 맨 처음 열린 가방
	//     at 파일명.js:34
	//     → 세번째 끝 (스택에서 팝)
	//   → 두번째 끝 (스택에서 팝)
	// → 첫번째 끝 (스택에서 팝)
	// ================================================================================

	// [2단계: 스택 한계 테스트 (실험 1 & 2)]

	// 함수가 몇 번이나 쌓였는지 기록할 카운터 변수
	let 깊이 = 0;

	function 끝없이자기를부름() {
	  // 함수가 호출될 때마다 카운트를 1씩 증가
	  깊이 = 깊이 + 1;
	  // 함수가 종료되지 않은 상태에서 자기 자신을 다시 호출 (무한 누적)
	  끝없이자기를부름();
	}
	try {
	  // 스택을 한계까지 쌓는 실험 시작
	  끝없이자기를부름();
	} catch (e) {
	  // 스택 영역이 가득 차면 RangeError가 발생하며 catch문으로 이동합니다.
	  // 함수 내부에 변수가 많을수록 한 칸의 용량이 커져 '터진 깊이' 숫자가 줄어듭니다.
	  console.log(`\n[실험 결과] 터진 깊이: ${깊이}번 만에 터짐 / 에러명: ${e.name}`);
	}
	// ================================================================================
	// [▼ 2단계 콘솔 실제 출력 결과창 ▼]
	//
	// [실험 결과] 터진 깊이: 10456번 만에 터짐 / 에러명: RangeError
	// ================================================================================
	// --------------------------------------------------------------------------------
	// new Error()의 원래 목적: 프로그램에 문제가 생겼을 때 "어디서 왜 고장 났는지" 상세 정보를 담는 진짜 에러 주머니를 만드는 것
	// .stack의 원래 목적: 프로그램이 실제로 터졌을 때, 개발자가 고장 난 지점을 역추적할 수 있도록 함수 호출 경로를 로그로 보여주는 것
	// new Error()의 현재 목적: 진짜 에러를 터뜨리지 않고, 자바스크립트 엔진이 에러를 만들 때 콜스택 사진을 찍어준다는 특성만 쏙 빼먹기 위해 임시로 가짜 사진기를 만드는 것
	// .stack의 현재 목적: 프로그램은 멈추지 않은 상태에서, 현재 함수들이 어떤 순서로 스택에 이쁘게 쌓여있는지 콘솔창에 텍스트로 꺼내서 눈으로 확인하는 것
	// --------------------------------------------------------------------------------


	// --------------------------------------------------------------------------------
	// [중간 요약]
	// --------------------------------------------------------------------------------
	// 런타임의 정의 (엔진+호스트)
	// - 자바스크립트 엔진 안에는 타이머(setTimeout), 네트워크(fetch), 이벤트 등이 없다.
	// - 엔진은 오직 한 번에 하나의 일만 처리하는 '요리사' 역할이다.
	// - 타이머나 네트어ㅜ크 같은 기능은 브라우저나 Node.js 같은 '호스트 환경'이 대신 기다려주는 주방 설비이다.

	// 엔진의안쪽 (콜스택 vs 힙)
	// -콜스택(Call stack) : 크기가 고정된 데이터와 실행 중인 함수 정보(실행 컨텍스트)를 LIFO 방식으로 엄격하게 쌓아두는 공간 (유한공간)
	// -힙(Heap) : 크기가 언제든 변할 수 있는 객체, 배열, 함수 등이 순서 없이 자유롭게 저장되는 대형 메모리 창고. 변수에는 힙으 주소(참조)가 저장

	// 싱글 스레드와 런투컴플리션(Run-to-completion)
	// - 자바스크립트는 하나의 콜스택을 사용하여 한 번에 딱 하나의 코드 조각만 실행
	// - 한 번 실행이 시작된 함수는 끝날 때까지 중간에 다른 코드가 절대 끼어들 수 없다.
	// - 따라서 연산이 너무 무겁고 긴 코드가 스택을 붙잡고 있으면 화면 전체가 얼어버리게 된다.

	// 무대감독 이벤트 루프와 두 개의 대기열(큐)
	// - 1단계: 콜스택이 완전히 비어있는지 먼저 확인
	// - 2단계: '마이크로태스트 큐(Promise 콜백 등)'에 대기가 있다면, 이 큐가 완전히 빌 때까지 새로 추가되는 것까지 포함해서 전부 실행
	// - 3단계: 마이크로태스크가 전부 비었을 때만 '태스크 큐(setTimeout 등)'에서 딱 하나를 꺼내 스택으로 보낸다.
	// - 결론: setTimeout(fn,0)을 해도 동기 코드가 끝나고, Promise 콜백들까지 전부 다 처리된 후에야 타이머 콜백이 실행되는 이유가 바로 우선순위 법칙 때문이다.
	// --------------------------------------------------------------------------------

	// --------------------------------------------------------------------------------
	// [힙 - 객체가 사는 창고]
	// --------------------------------------------------------------------------------
	// 힙(heap)은 원래 쌓아둔 더미라는 뜻이지만, 스택과 달리 순서 없이 흩어져 저장되는 메모리 영역을 말한다.
	// 스택에는 실행 정보와 크기가 고정된 값이 들어갑니다. 넣고 뺴는 순서가 엄격하다.
	// 힙에는 객체,배열,함수처럼 크기가 가변적인 것들이 들어간다. 순서가 없어서 아무 데나 놓고 주소로 찾아온다.
	// 스택은 책상 위에 쌓은 서류철(순서대로), 힙은 창고(선반 번호를 알면 아무 데나 바로 접근)
	// 변수에 객체를 담으면 객체 자체가 아니라 힙의 주소가 담긴다
	// 이 주소를 참조(reference)라고 부른다. 그래서 두 변수가 같은 객체를 가리킬 수 있다는 사실이 여기서 나온다.
	// 힙에서 더 이상 쓰이지 않는 객체를 자동으로 정리하는 장치가 GC(Garbage Collection, 가비지컬렉션 - 쓰레기수거)이다.
	// --------------------------------------------------------------------------------


	// --------------------------------------------------------------------------------
	// [싱글 스레드라는 말 바로잡기]
	// --------------------------------------------------------------------------------
	// Javascript는 싱글 스레드(single thread,단일 실행 흐름)은 그대로 받아들이면 두 가지 오해가 생긴다.
	// - Javascript는 느리다: X - 느린 것은 JS 코드로 계산을 오래하는 경우이며, 파일 읽기나 네트워크 요청 같은 기다림은 호스트가 대신 처리하므로 그동안 JS는 다른 일을 한다.
	// - 한 번에 하나만 하니 동시성이 없다: X - 병렬성(parallelism,물리적으로 동시에 실행)은 없지만 동시성(concurrency,여러 작업을 번갈아 진행)은 있습니다.
	// 정확한 표현은 (하나의 실행 흐름이 하나의 콜 스택을 쓰며, 한 번에 하나의 코드 조각만 실행한다.) - 이 실행 흐름을 스레드(thread)라고 부른다.
	// 다만 기다림이 필요한 작업은 호스트에 위임하고, 완료 시 실행할 콜백을 큐에 받아둔다.
	// --------------------------------------------------------------------------------

	// --------------------------------------------------------------------------------
	// [런투컴플리션(run-to-completion, 끝까지 실행)]
	// --------------------------------------------------------------------------------
	// 개념: 실행 중인 함수가 완전히 종료될 때까지 다른 작업이 끼어들 수 없는 규칙
	// 특징: 싱글 스레드인 JavaScript가 데이터 일관성을 유지하고 제어하기 쉬운 이유
	// 한계: 하나의 무거운 연산이 스택을 독점하면 브라우저나 화면이 완전히 먹통이 됨
	// --------------------------------------------------------------------------------

	// --------------------------------------------------------------------------------
	// [실습2 - 스레드 하나가 막히면은?]
	// --------------------------------------------------------------------------------
	// 순서: 1.동기 시작 -> 2.동기 계산 끝 -> 3.마이크로태스트 -> 4.타이머 태스크
	// --------------------------------------------------------------------------------
	// 1. 동기 코드 실행 (콜 스택에 즉시 진입)
	console.log("1. 동기 코드 시작");

	// 2. 태스크 큐(Task Queue)로 이동하는 일반 비동기 타이머
	setTimeout(function(){
		console.log('4. 타이머 콜백 - 0ms로 예약했지만 가장 마지막이다.')
	},0);

	// 3. 마이크로태스크 큐(MicrotaskQueue)로 이동하는 최우선 비동기
	Promise.resolve().then(function(){
		console.log('3.마이크로태스크 - 타이머보다 먼저 실행된다.')
	});

	// 4. 의도적으로 오래 걸리는 동기 연산을 실행하여 스레드를 점유한다. (블로킹)
	const 시작 = Date.now();
	let 합계 = 0;
	for ( let i = 0; i < 20000000; i = i + 1 ){
		합계 = 합계 + i;
	}
	const 걸린시간 = Date.now() - 시작;

	// 5.연산이 끝날 때가지 런투컴플리션 규칙에 의해 위 비동기 콜백들은 대기한다.
	console.log("2.동기 계산 끝 - 약 " +걸린시간 + "ms동안 스레드를 붙잡음");
	// --------------------------------------------------------------------------------
	// (1) loop 횟수를 늘리거나 줄여도 1 -> 2 -> 3 -> 4 출력 순서는 절대 바뀌지 않습니다.
	// (2) setTimeout(f, 0)은 '즉시 실행'이 아니라 '최소 대기 시간 후 큐 진입'을 뜻합니다.
	// (3) 콜 스택이 비면, 이벤트 루프는 마이크로태스크(Promise)를 타이머보다 먼저 처리합니다.
	// --------------------------------------------------------------------------------


	// --------------------------------------------------------------------------------
	// [이벤트 루프(Event Loop)의 4단계 무한 순환 규칙]
	// --------------------------------------------------------------------------------
	// 개념: 콜 스택과 비동기 큐들을 감시하면 코드를 순서대로 실행시키는 무대감독 장치
  // 특성: 웹페이지나 실행 환경이 살아있는 내내 1~4단계를 무한 반복 (Loop)
	// --------------------------------------------------------------------------------
	// 1단계[콜 스택 검사]:
	// - 현재 실행 중인 코드가 있는지 확인 (비어있지 않으면 끝날 때까지 대기)
	// - 이 단계 덕분에 실행 중인 동기 코드가 절대 끊기지 않음 (런투컴플리션)
	// --------------------------------------------------------------------------------
	// 2단계[마이크로태스크 큐 전멸]:
	// - Promise.then 이나 queueMicrotask 같은 우선 대기열을 확인
	// - 큐가 완전히 텅 빌 때까지 중간에 새로 추가된 것까지 전부 꺼내서 실행
	// --------------------------------------------------------------------------------
	// 3단계[태스크 큐 단 한 개]:
	// - setTimeout 타이머나 클릭 이벤트 핸들러 같은 일반 대기열을 확인
	// 마이크로와 달리 큐에서 '딱 하나만' 꺼내서 스택으로 올리고 바로 다음 단계로 이동
	// --------------------------------------------------------------------------------
	// 4단계[원점으로 루프]:
	// - 다시 1단계로 돌아가 스택 검사부터 순환을 무한히 재시작
	// --------------------------------------------------------------------------------
	// ※ 주의사항
	// - 2단계(마이크로큐) 내부에서 또 마이크로태스크를 무한히 생성하는 코드를 짜면, 3단계로 영영 차례가 넘어가지 않아 화면 갱신이 멈추고 먹통이 된다.
	// - 따라서 무거운 연산 작업은 setTimeout을 통해 일반 태스크로 쪼개 넣어야 안전함.
	// --------------------------------------------------------------------------------
	// --------------------------------------------------------------------------------

	// --------------------------------------------------------------------------------
	// [태스크와 마이크로태스크 - 두 대기열의 차이]
	// --------------------------------------------------------------------------------
	// 1. 태스크 (Task / 매크로태스크)
	// - 대표 예시: setTimeout, setInterval, DOM 이벤트 핸들러 등
	// - 정의 주체: 주로 브라우저나 Node.js 같은 호스트 환경
	// - 실행 규칙: 이벤트 루프 한 사이클당 큐에서 '딱 하나만' 꺼내서 실행
	// - 우선 순위: 낮음 (마이크로태스크 큐가 완전히 비어야만 순서가 돌아옴)
	// --------------------------------------------------------------------------------
	// 2. 마이크로태스크 (Microtask / 명세상 잡(Job) 큐)
	// - 대표 예시: Promise의 then/catch/finally, queueMicrotask 등
	// - 정의 주체: ECMAScript 공식 명세 표준 엔진 스펙
	// - 실행 규칙: 이벤트 루프 나 사이클 동안 큐가 '텅 빌 때까지 전부' 다 꺼내서 실행
	// - 우선 순위: 높음 (일반 태스크보다 무조건 먼저 가로채서 처리됨)
	// --------------------------------------------------------------------------------
	// ※ 비동기 처리를 하다가 화면이 멈출 때
	// - 마이크로태스크 콜백 내부에서 또 마이크로태스크를 무한히 호출하면, 큐가 빌 때까지 처리하는 규칙 때문에 일반 태스크(화면 갱신 등)로 순서가 못 넘어감.
	// - 반대로 무거운 동기 연산 작업을 setTimeout으로 감싸서 쪼개 넣으면, 루프가 한 번 돌 때마다 브라우저가 화면 갱신을 끼워 넣을 수 있어 먹통을 방지함.
	// --------------------------------------------------------------------------------

	// --------------------------------------------------------------------------------
	// [마무리 정리]
	// --------------------------------------------------------------------------------
	// 1.런타임 환경 일체 (Runtime)
	// -> 엔진(V8코어: 콜스택 + 힙)과 호스트(브라우저/Node.js 능력이 얹어진 구조)의 결합
	// -> setTimeout, fetch, DOM 제어 등은 엔진 명세가 아닌 호스트가 지원하는 설비임
	// --------------------------------------------------------------------------------
	// 2. 엔진의 메모리 영역 구조
	// -> 콜 스택(Call stack): 실행 중인 함수를 유한하게 쌓아 관리하는 LIFO(접시탑) 구조
	// -> 힙(Heap): 크기가 가변적인 객체, 배열, 함수들이 무작위로 할당되는 창고 공간
	// --------------------------------------------------------------------------------
	// 3. 싱글 스레드와 동시성 제어
	// -> 자바스크립트는 하나의 콜 스택으로 한 번에 단 하나의 코드 조각만 실행 가능함
	// -> 런투컴플리션(Run-to-completion): 실행된 코드는 중간에 끊기지 않고 끝까지 동작
	// --------------------------------------------------------------------------------
	// 4. 비동기 큐와 이벤트 루프 절대 원칙
	// -> 콜 스택이 텅 빈 시점에 무대 감독인 '이벤트 루프'가 기동을 시작함
	// -> 우선순위: 마이크로태스크(Promise) ' 전부 전멸' 처리 -> 태스크(타이머) '단 하나만' 처리
	// --------------------------------------------------------------------------------
}

