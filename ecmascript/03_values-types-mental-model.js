export function render() {
  // ------------------------------------------------------------------------------------------
  // [meta]
  // ------------------------------------------------------------------------------------------
  // 내용: JavaScript의 값과 타입, 원시값과 객체, 참조와 동일성을 확인한다.
  // 링크: https://zeno.it.kr/javascript/ECMAscript/03_values-types-mental-model
  // 배우고자 하는 것:
  // - 원시값과 객체의 차이를 이해한다.
  // - 객체는 참조를 통해 다뤄진다는 점을 확인한다.
  // - === 비교에서 값과 참조가 어떻게 다른지 확인한다.
  // ------------------------------------------------------------------------------------------

  // ------------------------------------------------------------------------------------------
  // [용어정리]
  // - Primitive: string, number, boolean, null, undefined, bigint, symbol 같은 원시값
  // - Object: 여러 값을 담을 수 있는 객체
  // - Reference: 객체가 저장된 위치를 가리키는 참조
  // - Identity: 두 변수가 같은 객체를 가리키는지에 대한 동일성
  // ------------------------------------------------------------------------------------------

  // ------------------------------------------------------------------------------------------
  // [1]
  // ------------------------------------------------------------------------------------------
  // 내용: 원시값은 값을 복사한다.
  //
  // 결과:
  // a → 10
  // b → 20
  // ------------------------------------------------------------------------------------------

  let a = 10;
  let b = a;

  b = 20;

  console.log(a);
  console.log(b);

  // ------------------------------------------------------------------------------------------
  // [2]
  // ------------------------------------------------------------------------------------------
  // 내용: 객체를 변수에 대입하면 같은 객체를 참조한다.
  //       copiedUser를 수정하면 user에서도 변경된 값이 보인다.
  //
  // 결과:
  // user.name       → Lee
  // copiedUser.name → Lee
  // ------------------------------------------------------------------------------------------

  const user = { name: 'Kim' };
  const copiedUser = user;

  copiedUser.name = 'Lee';

  console.log(user.name);
  console.log(copiedUser.name);

  // ------------------------------------------------------------------------------------------
  // [3]
  // ------------------------------------------------------------------------------------------
  // 내용: 같은 내용을 가진 원시값은 === 비교에서 true가 된다.
  //
  // 결과:
  // true
  // ------------------------------------------------------------------------------------------

  const value1 = 'JavaScript';
  const value2 = 'JavaScript';

  console.log(value1 === value2);

  // ------------------------------------------------------------------------------------------
  // [4]
  // ------------------------------------------------------------------------------------------
  // 내용: 내용이 같은 객체라도 서로 다른 객체라면 === 비교 결과는 false다.
  //       객체는 내용이 아니라 같은 객체를 참조하는지 비교한다.
  //
  // 결과:
  // false
  // ------------------------------------------------------------------------------------------

  const object1 = { name: 'Kim' };
  const object2 = { name: 'Kim' };

  console.log(object1 === object2);

  // ------------------------------------------------------------------------------------------
  // [5]
  // ------------------------------------------------------------------------------------------
  // 내용: 두 변수가 같은 객체를 참조하면 === 비교 결과는 true다.
  //
  // 결과:
  // true
  // ------------------------------------------------------------------------------------------

  const object3 = { name: 'Kim' };
  const object4 = object3;

  console.log(object3 === object4);

  // ------------------------------------------------------------------------------------------
  // [6]
  // ------------------------------------------------------------------------------------------
  // 내용: typeof를 이용해 기본 타입을 확인한다.
  //
  // 결과:
  // string
  // number
  // boolean
  // undefined
  // object
  // object
  // ------------------------------------------------------------------------------------------

  console.log(typeof 'hello');
  console.log(typeof 100);
  console.log(typeof true);
  console.log(typeof undefined);
  console.log(typeof null);
  console.log(typeof { name: 'Kim' });
}

// ------------------------------------------------------------------------------------------
// [배운 것]
// - 원시값을 다른 변수에 대입하면 값이 복사된다.
// - 객체를 다른 변수에 대입하면 같은 객체를 참조한다.
// - 원시값의 === 비교는 값을 비교한다.
// - 객체의 === 비교는 같은 객체를 참조하는지 비교한다.
// - typeof null의 결과는 역사적인 이유로 object가 나온다.
// ------------------------------------------------------------------------------------------
