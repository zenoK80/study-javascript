export function render() {
  // ------------------------------------------------------------------------------------------
  // [meta]
  // ------------------------------------------------------------------------------------------
  // 내용: 비교, 논리 연산자, 단축 평가, 옵셔널 체이닝을 확인한다.
  // 링크: https://zeno.it.kr/javascript/ECMAscript/06_operators-and-short-circuit
  // 배우고자 하는 것:
  // - == 와 === 의 차이를 확인한다.
  // - &&, || 단축 평가 동작을 이해한다.
  // - ?? 와 || 의 차이를 확인한다.
  // - ?. 로 안전하게 프로퍼티에 접근한다.
  // ------------------------------------------------------------------------------------------

  // ------------------------------------------------------------------------------------------
  // [용어정리]
  // - ===: 타입 변환 없이 값과 타입을 비교
  // - Short Circuit: 결과가 결정되면 뒤의 표현식을 실행하지 않는 동작
  // - ?? : null 또는 undefined일 때만 오른쪽 값을 사용
  // - ?. : 값이 null/undefined이면 오류 대신 undefined를 반환
  // ------------------------------------------------------------------------------------------

  // ------------------------------------------------------------------------------------------
  // [1]
  // ------------------------------------------------------------------------------------------
  // 내용: == 와 === 비교 차이를 확인한다.
  //
  // 결과:
  // "1" == 1  → true
  // "1" === 1 → false
  // ------------------------------------------------------------------------------------------

  console.log('1' == 1);
  console.log('1' === 1);

  // ------------------------------------------------------------------------------------------
  // [2]
  // ------------------------------------------------------------------------------------------
  // 내용: && 는 왼쪽 값이 Falsy면 바로 왼쪽 값을 반환한다.
  //       Truthy면 오른쪽 표현식까지 실행한다.
  //
  // 결과:
  // false
  // 실행됨
  // ------------------------------------------------------------------------------------------

  console.log(false && '실행됨');
  console.log(true && '실행됨');

  // ------------------------------------------------------------------------------------------
  // [3]
  // ------------------------------------------------------------------------------------------
  // 내용: || 는 왼쪽 값이 Truthy면 바로 왼쪽 값을 반환한다.
  //       Falsy면 오른쪽 값을 사용한다.
  //
  // 결과:
  // JavaScript
  // 기본값
  // ------------------------------------------------------------------------------------------

  console.log('JavaScript' || '기본값');
  console.log('' || '기본값');

  // ------------------------------------------------------------------------------------------
  // [4]
  // ------------------------------------------------------------------------------------------
  // 내용: ?? 는 null 또는 undefined일 때만 오른쪽 값을 사용한다.
  //       0이나 빈 문자열은 유효한 값으로 취급한다.
  //
  // 결과:
  // 0
  // ""
  // 기본값
  // ------------------------------------------------------------------------------------------

  console.log(0 ?? '기본값');
  console.log('' ?? '기본값');
  console.log(null ?? '기본값');

  // ------------------------------------------------------------------------------------------
  // [5]
  // ------------------------------------------------------------------------------------------
  // 내용: || 와 ?? 의 차이를 확인한다.
  //
  // 결과:
  // 0 || 10  → 10
  // 0 ?? 10  → 0
  // ------------------------------------------------------------------------------------------

  console.log(0 || 10);
  console.log(0 ?? 10);

  // ------------------------------------------------------------------------------------------
  // [6]
  // ------------------------------------------------------------------------------------------
  // 내용: Optional Chaining(?.)으로 존재하지 않는 프로퍼티에 안전하게 접근한다.
  //
  // 결과:
  // Seoul
  // undefined
  // ------------------------------------------------------------------------------------------

  const user = {
    name: 'Kim',
    address: {
      city: 'Seoul'
    }
  };

  console.log(user.address?.city);
  console.log(user.company?.name);

  // ------------------------------------------------------------------------------------------
  // [7]
  // ------------------------------------------------------------------------------------------
  // 내용: ?. 없이 존재하지 않는 중첩 프로퍼티에 접근하면 오류가 발생한다.
  //
  // 결과:
  // TypeError
  // ------------------------------------------------------------------------------------------

  try {
    console.log(user.company.name);
  } catch (error) {
    console.log(error.name);
  }
}

// ------------------------------------------------------------------------------------------
// [배운 것]
// - 비교에는 가능하면 === 를 사용한다.
// - && 와 || 는 결과가 결정되면 뒤의 표현식을 실행하지 않는다.
// - || 는 Falsy 전체를 기본값 처리한다.
// - ?? 는 null과 undefined만 기본값 처리한다.
// - ?. 를 사용하면 없는 중첩 프로퍼티에 안전하게 접근할 수 있다.
// ------------------------------------------------------------------------------------------
