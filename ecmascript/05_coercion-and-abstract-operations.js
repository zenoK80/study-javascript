export function render() {
  // ------------------------------------------------------------------------------------------
  // [meta]
  // ------------------------------------------------------------------------------------------
  // 내용: JavaScript의 타입 강제 변환과 내부 변환 규칙을 확인한다.
  // 링크: https://zeno.it.kr/javascript/ECMAscript/05_coercion-and-abstract-operations
  // 배우고자 하는 것:
  // - 문자열, 숫자, 불리언이 자동으로 어떻게 변환되는지 확인한다.
  // - ToPrimitive, ToNumber, ToBoolean 개념을 이해한다.
  // - == 비교에서 타입 강제 변환이 어떻게 일어나는지 확인한다.
  // ------------------------------------------------------------------------------------------

  // ------------------------------------------------------------------------------------------
  // [용어정리]
  // - Type Coercion: JavaScript가 값을 다른 타입으로 자동 변환하는 것
  // - ToPrimitive: 객체를 string, number 같은 원시값으로 변환하는 내부 과정
  // - ToNumber: 값을 number 타입으로 변환하는 내부 과정
  // - ToBoolean: 값을 true 또는 false로 변환하는 내부 과정
  // - Truthy / Falsy: Boolean 변환 시 true / false로 평가되는 값
  // ------------------------------------------------------------------------------------------

  // ------------------------------------------------------------------------------------------
  // [1]
  // ------------------------------------------------------------------------------------------
  // 내용: + 연산자는 문자열이 포함되면 문자열 연결을 수행한다.
  //
  // 결과:
  // 10 + "20" → "1020"
  // ------------------------------------------------------------------------------------------

  console.log(10 + '20');

  // ------------------------------------------------------------------------------------------
  // [2]
  // ------------------------------------------------------------------------------------------
  // 내용: -, *, / 연산자는 문자열을 숫자로 변환한 뒤 계산한다.
  //
  // 결과:
  // "20" - 10 → 10
  // "5" * 2   → 10
  // "20" / 2  → 10
  // ------------------------------------------------------------------------------------------

  console.log('20' - 10);
  console.log('5' * 2);
  console.log('20' / 2);

  // ------------------------------------------------------------------------------------------
  // [3]
  // ------------------------------------------------------------------------------------------
  // 내용: Number()를 이용해 값을 숫자로 변환한다.
  //
  // 결과:
  // Number("10")        → 10
  // Number("")          → 0
  // Number(true)        → 1
  // Number(false)       → 0
  // Number(undefined)   → NaN
  // Number(null)        → 0
  // ------------------------------------------------------------------------------------------

  console.log(Number('10'));
  console.log(Number(''));
  console.log(Number(true));
  console.log(Number(false));
  console.log(Number(undefined));
  console.log(Number(null));

  // ------------------------------------------------------------------------------------------
  // [4]
  // ------------------------------------------------------------------------------------------
  // 내용: Boolean()을 이용해 Truthy와 Falsy 값을 확인한다.
  //
  // Falsy:
  // false, 0, "", null, undefined, NaN
  //
  // 결과:
  // Boolean(0)          → false
  // Boolean("")         → false
  // Boolean(null)       → false
  // Boolean(undefined)  → false
  // Boolean([])         → true
  // Boolean({})         → true
  // ------------------------------------------------------------------------------------------

  console.log(Boolean(0));
  console.log(Boolean(''));
  console.log(Boolean(null));
  console.log(Boolean(undefined));
  console.log(Boolean([]));
  console.log(Boolean({}));

  // ------------------------------------------------------------------------------------------
  // [5]
  // ------------------------------------------------------------------------------------------
  // 내용: 객체를 문자열과 더하면 객체가 원시값으로 변환된 뒤 연산된다.
  //       일반 객체는 기본적으로 "[object Object]" 문자열로 변환될 수 있다.
  //
  // 결과:
  // "[object Object]1"
  // ------------------------------------------------------------------------------------------

  const object = {};

  console.log(object + 1);

  // ------------------------------------------------------------------------------------------
  // [6]
  // ------------------------------------------------------------------------------------------
  // 내용: 배열도 연산 전에 원시값으로 변환된다.
  //
  // 결과:
  // [1, 2] + 3 → "1,23"
  // [] + 1     → "1"
  // ------------------------------------------------------------------------------------------

  console.log([1, 2] + 3);
  console.log([] + 1);

  // ------------------------------------------------------------------------------------------
  // [7]
  // ------------------------------------------------------------------------------------------
  // 내용: == 연산자는 타입이 다르면 강제 변환 후 비교한다.
  //       === 연산자는 타입 변환 없이 타입과 값을 모두 비교한다.
  //
  // 결과:
  // 0 == false   → true
  // 0 === false  → false
  // "1" == 1     → true
  // "1" === 1    → false
  // ------------------------------------------------------------------------------------------

  console.log(0 == false);
  console.log(0 === false);
  console.log('1' == 1);
  console.log('1' === 1);
}

// ------------------------------------------------------------------------------------------
// [배운 것]
// - JavaScript는 연산 상황에 따라 값을 자동으로 다른 타입으로 변환할 수 있다.
// - +는 문자열 연결이 발생할 수 있고, -, *, /는 숫자 변환이 일어난다.
// - ToBoolean에서 0, "", null, undefined, NaN 등은 Falsy다.
// - 객체와 배열도 연산 전에 원시값으로 변환될 수 있다.
// - ==는 타입 강제 변환을 수행하고, ===는 수행하지 않는다.
// ------------------------------------------------------------------------------------------
